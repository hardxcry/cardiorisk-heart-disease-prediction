"""Render reports/RESULTS.md from reports/metrics.json so every published number is traceable.

Run:  python -m heartrisk.report
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]


def ci(m: dict, k: str, pct: bool = False) -> str:
    lo, hi = m["ci95"][k]
    f = (lambda v: f"{v:.1%}") if pct else (lambda v: f"{v:.3f}")
    return f"{f(m[k])} ({f(lo)} to {f(hi)})"


def main() -> None:
    d = json.loads((ROOT / "reports" / "metrics.json").read_text())
    best = d["selected_model"]
    L = ["# Results", "", "Generated by `python -m heartrisk.report` from `reports/metrics.json`.", ""]

    ds = d["dataset"]
    L += ["## Cohort", "", f"{ds['n']} patients, disease prevalence {ds['prevalence']:.1%}.", "",
          "| Site | Patients | Prevalence |", "|---|---|---|"]
    L += [f"| {s} | {v['n']} | {v['prevalence']:.1%} |" for s, v in ds["per_site"].items()]

    L += ["", "## Internal validation (5x5 repeated stratified CV, pooled sites)", "",
          "Values are point estimates with bootstrap 95% confidence intervals.", "",
          "| Model | AUROC | AUPRC | Brier | Sensitivity | Specificity | Cal. slope |",
          "|---|---|---|---|---|---|---|"]
    for name, m in d["internal_cv"].items():
        star = " **(selected)**" if name == best else ""
        L.append(f"| {name}{star} | {ci(m, 'auroc')} | {ci(m, 'auprc')} | {ci(m, 'brier')} | "
                 f"{ci(m, 'sensitivity', True)} | {ci(m, 'specificity', True)} | "
                 f"{m['calibration_slope']:.2f} |")

    L += ["", "## External validation (leave one hospital out)", "",
          "Each column is a hospital the model never saw during training. AUROC shown.", "",
          "| Model | " + " | ".join(ds["per_site"]) + " | Mean |",
          "|---|" + "---|" * (len(ds["per_site"]) + 1)]
    for name, sites in d["external_loso"].items():
        aucs = [v["auroc"] for v in sites.values()]
        L.append(f"| {name} | " + " | ".join(f"{a:.3f}" for a in aucs) + f" | {np.mean(aucs):.3f} |")

    L += ["", f"### {best} on each unseen hospital (threshold {d['internal_cv'][best]['threshold']:.3f})",
          "", "| Site | n | AUROC | Sensitivity | Specificity | Brier | Cal. slope |",
          "|---|---|---|---|---|---|---|"]
    for s, v in d["external_loso"][best].items():
        L.append(f"| {s} | {v['n']} | {v['auroc']:.3f} | {v['sensitivity']:.1%} | "
                 f"{v['specificity']:.1%} | {v['brier']:.3f} | {v['calibration_slope']:.2f} |")

    L += ["", "## Subgroup audit (selected model, internal CV predictions)", "",
          "| Subgroup | n | Prevalence | AUROC | Sensitivity | Specificity |", "|---|---|---|---|---|---|"]
    for g, v in d["subgroups"].items():
        L.append(f"| {g} | {v['n']} | {v['prevalence']:.1%} | {v['auroc']:.3f} | "
                 f"{v['sensitivity']:.1%} | {v['specificity']:.1%} |")

    L += ["", "## Missing data by site (% of patients)", "",
          "| Feature | " + " | ".join(ds["per_site"]) + " |", "|---|" + "---|" * len(ds["per_site"])]
    feats = next(iter(ds["missing_pct"].values()))
    for f in feats:
        L.append(f"| {f} | " + " | ".join(f"{ds['missing_pct'][s][f]:.0f}" for s in ds["per_site"]) + " |")

    L += ["", "## Global feature importance (drop in AUROC when shuffled)", "",
          "| Feature | Importance |", "|---|---|"]
    L += [f"| {f} | {v:.4f} |" for f, v in d["permutation_importance"].items()]

    (ROOT / "reports" / "RESULTS.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote reports/RESULTS.md")


if __name__ == "__main__":
    main()
